//! Evidence storage and chain of custody.
//!
//! Original captures live on the evidence volume (never in PostgreSQL), are written
//! exactly once (`create_new`), made read-only, hashed with SHA-256, and every
//! ingestion / analysis / access / export / verification is recorded in the
//! append-only `chain_of_custody` and `evidence_hashes` tables.
use std::path::{Path, PathBuf};

use rand::{rngs::OsRng, RngCore};
use serde_json::Value;
use sha2::{Digest, Sha256};
use sqlx::PgPool;
use tokio::io::AsyncReadExt;
use uuid::Uuid;

use crate::{auth::RequestMeta, error::AppError};

/// `EV-YYYYMMDD-<12 uppercase hex>` (matches the DB CHECK constraint).
pub fn new_evidence_id() -> String {
    let mut b = [0u8; 6];
    OsRng.fill_bytes(&mut b);
    let hex: String = b.iter().map(|x| format!("{x:02X}")).collect();
    format!("EV-{}-{hex}", chrono::Utc::now().format("%Y%m%d"))
}

/// Relative storage path for a job's original capture.
pub fn relative_path(job_id: Uuid, ext: &str) -> String {
    format!("{job_id}/original.{ext}")
}

pub fn absolute_path(root: &Path, relative: &str) -> Result<PathBuf, AppError> {
    // storage_path is generated by us, but never trust a DB value to stay inside the root.
    if relative.contains("..") || relative.starts_with('/') {
        return Err(AppError::internal("unsafe evidence path"));
    }
    Ok(root.join(relative))
}

/// PCAP / PCAPNG magic numbers. Returns the extension to store under.
pub fn detect_capture_kind(head: &[u8]) -> Option<&'static str> {
    if head.len() < 4 {
        return None;
    }
    match head[..4] {
        [0xd4, 0xc3, 0xb2, 0xa1] | [0xa1, 0xb2, 0xc3, 0xd4] // pcap, microsecond
        | [0x4d, 0x3c, 0xb2, 0xa1] | [0xa1, 0xb2, 0x3c, 0x4d] => Some("pcap"), // pcap, nanosecond
        [0x0a, 0x0d, 0x0d, 0x0a] => Some("pcapng"),
        _ => None,
    }
}

pub async fn sha256_file(path: &Path) -> std::io::Result<(Vec<u8>, u64)> {
    let mut f = tokio::fs::File::open(path).await?;
    let mut h = Sha256::new();
    let mut buf = vec![0u8; 256 * 1024];
    let mut total = 0u64;
    loop {
        let n = f.read(&mut buf).await?;
        if n == 0 {
            break;
        }
        h.update(&buf[..n]);
        total += n as u64;
    }
    Ok((h.finalize().to_vec(), total))
}

pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// Make a stored capture read-only (0400) so it cannot be modified in place.
pub async fn seal(path: &Path) -> std::io::Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        tokio::fs::set_permissions(path, std::fs::Permissions::from_mode(0o400)).await?;
    }
    #[cfg(not(unix))]
    {
        let mut p = tokio::fs::metadata(path).await?.permissions();
        p.set_readonly(true);
        tokio::fs::set_permissions(path, p).await?;
    }
    Ok(())
}

/// Who performed a custody action.
pub struct Actor<'a> {
    pub id: Option<Uuid>,
    pub label: &'a str,
}

pub async fn record_custody(
    pool: &PgPool,
    artifact_id: Uuid,
    action: &str,
    actor: &Actor<'_>,
    meta: Option<&RequestMeta>,
    detail: Value,
) -> Result<(), AppError> {
    sqlx::query(
        "INSERT INTO chain_of_custody (artifact_id, action, actor_id, actor_label, ip_address, detail) \
         VALUES ($1, $2::text::custody_action, $3, $4, $5::text::inet, $6)",
    )
    .bind(artifact_id)
    .bind(action)
    .bind(actor.id)
    .bind(actor.label)
    .bind(meta.and_then(|m| m.ip.as_deref()))
    .bind(detail)
    .execute(pool)
    .await?;
    Ok(())
}

/// Result of an integrity check.
pub struct Verification {
    pub ok: bool,
    pub expected: Vec<u8>,
    pub actual: Vec<u8>,
}

/// Re-hash the stored file and compare with the hash recorded at ingestion. The
/// outcome is always recorded (append-only), whether it matched or not.
pub async fn verify_artifact(
    pool: &PgPool,
    root: &Path,
    artifact_id: Uuid,
    actor: &Actor<'_>,
    meta: Option<&RequestMeta>,
) -> Result<Verification, AppError> {
    let (storage_path, expected): (String, Vec<u8>) =
        sqlx::query_as("SELECT storage_path, sha256 FROM evidence_artifacts WHERE id = $1")
            .bind(artifact_id)
            .fetch_optional(pool)
            .await?
            .ok_or(AppError::NotFound)?;
    let path = absolute_path(root, &storage_path)?;
    let actual = match sha256_file(&path).await {
        Ok((h, _)) => h,
        Err(_) => Vec::new(), // missing/unreadable counts as a failed verification
    };
    let ok = actual == expected;
    sqlx::query(
        "INSERT INTO evidence_hashes (artifact_id, digest, matches_original, computed_by) VALUES ($1, $2, $3, $4)",
    )
    .bind(artifact_id)
    .bind(if actual.len() == 32 { actual.clone() } else { vec![0u8; 32] })
    .bind(ok)
    .bind(actor.id)
    .execute(pool)
    .await?;
    record_custody(
        pool,
        artifact_id,
        if ok {
            "verified"
        } else {
            "verification_failed"
        },
        actor,
        meta,
        serde_json::json!({"expected": hex(&expected), "actual": hex(&actual)}),
    )
    .await?;
    Ok(Verification {
        ok,
        expected,
        actual,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn evidence_ids_match_db_format() {
        let id = new_evidence_id();
        assert!(id.starts_with("EV-"));
        assert_eq!(id.len(), "EV-20260101-ABCDEF012345".len());
        assert!(id[12..]
            .chars()
            .all(|c| c.is_ascii_hexdigit() && !c.is_ascii_lowercase()));
        assert_ne!(new_evidence_id(), id);
    }

    #[test]
    fn magic_detection() {
        assert_eq!(
            detect_capture_kind(&[0xd4, 0xc3, 0xb2, 0xa1, 0]),
            Some("pcap")
        );
        assert_eq!(detect_capture_kind(&[0xa1, 0xb2, 0xc3, 0xd4]), Some("pcap"));
        assert_eq!(
            detect_capture_kind(&[0x0a, 0x0d, 0x0d, 0x0a]),
            Some("pcapng")
        );
        assert_eq!(detect_capture_kind(b"MZ\x90\x00"), None);
        assert_eq!(detect_capture_kind(&[1, 2]), None);
    }

    #[test]
    fn paths_cannot_escape_the_root() {
        let root = Path::new("/evidence");
        assert!(absolute_path(root, "abc/original.pcap").is_ok());
        assert!(absolute_path(root, "../etc/passwd").is_err());
        assert!(absolute_path(root, "/etc/passwd").is_err());
    }

    #[tokio::test]
    async fn hashing_matches_known_vector() {
        let p = std::env::temp_dir().join(format!("neto-test-{}", Uuid::new_v4()));
        tokio::fs::write(&p, b"abc").await.unwrap();
        let (h, n) = sha256_file(&p).await.unwrap();
        tokio::fs::remove_file(&p).await.unwrap();
        assert_eq!(n, 3);
        assert_eq!(
            hex(&h),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }
}


#[derive(serde::Serialize, Clone, Debug)]
pub struct DiskMetrics {
    pub total_bytes: u64,
    pub available_bytes: u64,
    pub used_bytes: u64,
    pub used_percent: f64,
    pub evidence_dir_bytes: u64,
    pub evidence_file_count: u64,
    pub is_low_space: bool,
}

/// Query filesystem stats on path using libc statvfs.
pub fn get_disk_metrics(dir_path: &Path) -> Result<DiskMetrics, AppError> {
    use std::ffi::CString;
    use std::os::unix::ffi::OsStrExt;

    let c_path = CString::new(dir_path.as_os_str().as_bytes())
        .map_err(|_| AppError::internal("invalid path for statvfs"))?;

    let mut stat: libc::statvfs = unsafe { std::mem::zeroed() };
    let res = unsafe { libc::statvfs(c_path.as_ptr(), &mut stat) };
    if res != 0 {
        return Err(AppError::internal("failed to inspect filesystem stats"));
    }

    let frsize = stat.f_frsize as u64;
    let total_bytes = stat.f_blocks as u64 * frsize;
    let available_bytes = stat.f_bavail as u64 * frsize;
    let used_bytes = total_bytes.saturating_sub(stat.f_bfree as u64 * frsize);
    let used_percent = if total_bytes > 0 {
        ((total_bytes - available_bytes) as f64 / total_bytes as f64) * 100.0
    } else {
        0.0
    };

    // Calculate disk usage and file count in the evidence folder
    let mut evidence_dir_bytes = 0u64;
    let mut evidence_file_count = 0u64;
    if let Ok(entries) = std::fs::read_dir(dir_path) {
        for entry in entries.flatten() {
            if let Ok(meta) = entry.metadata() {
                if meta.is_file() {
                    evidence_dir_bytes += meta.len();
                    evidence_file_count += 1;
                } else if meta.is_dir() {
                    if let Ok(sub_entries) = std::fs::read_dir(entry.path()) {
                        for sub in sub_entries.flatten() {
                            if let Ok(sub_meta) = sub.metadata() {
                                if sub_meta.is_file() {
                                    evidence_dir_bytes += sub_meta.len();
                                    evidence_file_count += 1;
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    // Low space alert triggered if available free space is below 10%
    let is_low_space = used_percent >= 90.0 || available_bytes < 1024 * 1024 * 1024; // < 1 GiB or > 90%

    Ok(DiskMetrics {
        total_bytes,
        available_bytes,
        used_bytes,
        used_percent,
        evidence_dir_bytes,
        evidence_file_count,
        is_low_space,
    })
}


pub fn format_bytes(bytes: u64) -> String {
    const KIB: u64 = 1024;
    const MIB: u64 = 1024 * 1024;
    const GIB: u64 = 1024 * 1024 * 1024;

    if bytes >= GIB {
        format!("{:.2} GiB", bytes as f64 / GIB as f64)
    } else if bytes >= MIB {
        format!("{:.2} MiB", bytes as f64 / MIB as f64)
    } else if bytes >= KIB {
        format!("{:.2} KiB", bytes as f64 / KIB as f64)
    } else {
        format!("{bytes} B")
    }
}
